// Mock response shape for IT-Demand's API, e.g. GET /api/tickets.
//
// Tickets are assigned to a UNIT, not an employee — IT-Demand only knows
// which team owns the work. WorkLens is where a supervisor decides which employee on
// that team actually picks it up (see the tickets store for that bridge).

import type { Department } from "./types";

// Task lifecycle is deliberately just three states everywhere in the app.
export type TicketStatus = "In Progress" | "On Hold" | "Completed";
export const TICKET_STATUS_OPTIONS: TicketStatus[] = ["In Progress", "On Hold", "Completed"];
export type TicketPriority = "High" | "Medium" | "Low";

/** A frozen coverage plan created when a supervisor accepts a turnover request. The
 * covering employee takes exactly these days at exactly these hours — the same planned
 * daily distribution the owner already had — so temporarily changing who does the work
 * never compresses or reshapes the schedule. */
export interface TicketCoverage {
  /** Who is covering the owner during their absence. */
  coveringEmployeeId: string;
  /** The ticket's owner (kept explicit so intent survives an assignee change). */
  ownerId: string;
  ownerName: string;
  coveringName: string;
  /** The leave / turnover window, "26 Aug 2026" style (inclusive). */
  startDate: string;
  endDate: string;
  /** Exact working-day keys ("YYYY-MM-DD") the cover takes, with the owner's own
   * per-day planned hours for each — a snapshot, not recomputed. */
  allocations: { dateKey: string; hours: number }[];
  /** Total hours the cover is taking on = sum of `allocations[].hours`. */
  hours: number;
  createdAt: string;
}

export interface Ticket {
  id: string;
  title: string;
  description: string;
  status: TicketStatus;
  priority: TicketPriority;
  assignedUnit: Department;
  raisedDate: string;
  estimatedHours: number;
  slaHours: number;
  expectedResolutionDate: string;
  /** Set the moment status becomes "Completed" — the item's completion date, shown
   * across every view and cleared if it's moved back out of Completed. */
  resolvedDate: string | null;
  /** The hold window, captured when status is set to "On Hold" (both "26 Aug 2026"
   * style). An on-hold ticket still consumes capacity — it is not completed. */
  holdStartDate?: string | null;
  holdEndDate?: string | null;
  createdBy: string;
  assignedBy: string;
  /** Employees this ticket is assigned to in WorkLens (0–2). Seed data pre-assigns
   * most tickets so the demo has a realistic workload picture; the live store owns
   * this field thereafter. */
  assignedEmployeeIds?: string[];
  /** Time-boxed coverage: while `coverage` is set, the covering employee carries the
   * ticket's planned hours ONLY for the days inside the coverage window (e.g. the
   * owner's leave); the owner keeps it before and after. Ownership does not transfer. */
  coverage?: TicketCoverage | null;
  /** Skills this ticket calls for, when the category makes that clear — used to suggest
   * an owner. Left unset for generic tickets any team member could pick up. */
  relatedSkills?: string[];
  /** When co-assigned to 2 people, how the estimated effort is split between them
   * ({ employeeId: hours }). Absent / partial entries fall back to an even split.
   * The values always sum to `estimatedHours`. */
  effortSplit?: Record<string, number>;
  /** ISO timestamp of the last assignment / status change — drives the supervisor's
   * "most recent activity" ordering. */
  activityAt?: string;
  /** Optional prerequisite ticket. While it is not Completed, this ticket's work is
   * not scheduled before the prerequisite's due date. A single lightweight link, not
   * a dependency graph — supervisor-set on the task detail panel. */
  dependsOnTicketId?: string | null;
}

